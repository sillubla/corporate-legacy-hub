create table if not exists public.capsules (
  id uuid primary key default gen_random_uuid(),
  author_id uuid not null references public.profiles(id) on delete restrict,
  title text not null check (char_length(title) between 3 and 180),
  summary text not null check (char_length(summary) between 10 and 3000),
  format text not null check (format in ('audio', 'video', 'case')),
  category text not null check (char_length(category) between 2 and 100),
  duration_seconds integer check (duration_seconds is null or duration_seconds >= 0),
  media_path text,
  transcript text,
  status text not null default 'draft' check (status in ('draft', 'published', 'archived')),
  featured boolean not null default false,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint capsules_media_required_when_published check (
    status <> 'published'
    or format = 'case'
    or media_path is not null
  )
);

create table if not exists public.tags (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 60),
  slug text not null unique check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  created_at timestamptz not null default now()
);

create table if not exists public.capsule_tags (
  capsule_id uuid not null references public.capsules(id) on delete cascade,
  tag_id bigint not null references public.tags(id) on delete cascade,
  primary key (capsule_id, tag_id)
);

