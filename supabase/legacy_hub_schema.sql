-- Mantiene published_at alineado con el estado.
create or replace function public.set_capsule_published_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  if new.status = 'published' and (old.status is distinct from 'published' or new.published_at is null) then
    new.published_at = coalesce(new.published_at, now());
  end if;
  return new;
end;
$$;

drop trigger if exists capsules_set_published_at on public.capsules;
create trigger capsules_set_published_at
  before update on public.capsules
  for each row execute function public.set_capsule_published_at();

