create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Nuevo miembro',
  job_title text,
  department text,
  bio text,
  avatar_path text,
  years_of_experience integer check (years_of_experience is null or years_of_experience >= 0),
  is_expert boolean not null default false,
  is_admin boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, display_name, avatar_path)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'display_name', ''), 'Nuevo miembro'),
    nullif(new.raw_user_meta_data ->> 'avatar_path', '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

create or replace function public.protect_profile_privileges()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  if auth.uid() is not null
    and auth.uid() = old.id
    and (
      new.is_admin is distinct from old.is_admin
      or new.is_expert is distinct from old.is_expert
    )
  then
    raise exception 'No puedes modificar tus propios permisos.';
  end if;
  return new;
end;
$$;

