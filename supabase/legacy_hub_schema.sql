-- Ruta esperada: capsule-media/<user-id>/<capsule-id>/<archivo>
drop policy if exists "Authenticated users can read capsule media" on storage.objects;
create policy "Authenticated users can read capsule media"
  on storage.objects for select
  to authenticated
  using (
    bucket_id = 'capsule-media'
    and (
      (storage.foldername(name))[1] = auth.uid()::text
      or exists (
        select 1
        from public.capsules
        where capsules.media_path = storage.objects.name
          and capsules.status = 'published'
      )
    )
  );

drop policy if exists "Users can upload capsule media" on storage.objects;
create policy "Users can upload capsule media"
  on storage.objects for insert
  to authenticated
  with check (
    bucket_id = 'capsule-media'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

drop policy if exists "Users can update their capsule media" on storage.objects;
create policy "Users can update their capsule media"
  on storage.objects for update
  to authenticated
  using (
    bucket_id = 'capsule-media'
    and (storage.foldername(name))[1] = auth.uid()::text
  )
  with check (
    bucket_id = 'capsule-media'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

drop policy if exists "Users can delete their capsule media" on storage.objects;
create policy "Users can delete their capsule media"
  on storage.objects for delete
  to authenticated
  using (
    bucket_id = 'capsule-media'
